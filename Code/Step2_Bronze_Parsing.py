# MAGIC %md
# MAGIC # Step 2 — Bronze Parsing: JSON → Normalised Tables (Dynamic, Multi-Domain)
# MAGIC **Pipeline:** Dynamic MDM Platform | **Layer:** Bronze
# MAGIC
# MAGIC Reads from the generic `bronze.sland_mdm` landing table produced by Step 1
# MAGIC (which already tags every row with a content-detected `domain_code` —
# MAGIC `RETAIL` / `HEALTHCARE`) and parses the raw JSON into normalised Bronze
# MAGIC tables that both domains write into, side by side.
# MAGIC
# MAGIC ## Table Structure
# MAGIC
# MAGIC | Table | PK | FK | Source Nodes Merged |
# MAGIC |---|---|---|---|
# MAGIC | `bronze.sourceconsumer` | `src_id` (auto-increment) | `sln_id` → sland_mdm.sln_id | Header + Consumer/Patient + SourceSystem + BestRecord + PersonalData |
# MAGIC | `bronze.sourcemedia` | `srme_id` (auto-increment) | `srme_src_id` → sourceconsumer.src_id | ContactInformation → EMediaList |
# MAGIC | `bronze.sourcephone` | `srph_id` (auto-increment) | `srph_src_id` → sourceconsumer.src_id | ContactInformation → PhoneList |
# MAGIC | `bronze.sourceaddress` | `srad_id` (auto-increment) | `srad_src_id` → sourceconsumer.src_id | ContactInformation → AddressList |
# MAGIC | `bronze.sourceoptin` | `srop_id` (auto-increment) | `srop_src_id` → sourceconsumer.src_id | OptInList |
# MAGIC
# MAGIC ## Key design points
# MAGIC - **`src_id` is a real auto-increment PK** (`GENERATED BY DEFAULT AS IDENTITY`,
# MAGIC   not `ALWAYS`) — this lets us *compute* the next block of IDs in Python
# MAGIC   before writing, so the same `src_id` values are known and can be reused
# MAGIC   as the FK when building the child (media/phone/address/optin) DataFrames
# MAGIC   in the same run, without a second read-back from Delta.
# MAGIC - **`sln_id`** (the landing-table row id) is kept as a plain traceability
# MAGIC   column on `sourceconsumer`, separate from the `src_id` PK.
# MAGIC - **Domain-aware parsing**: `bronze.domain_config` tells us the JSON root
# MAGIC   entity per domain (`Consumer` vs `Patient`); a small in-notebook
# MAGIC   field-name map handles the handful of fields named differently between
# MAGIC   domains (e.g. `AssignedPersonnelCode` vs `AssignedPhysicianCode`). This
# MAGIC   map is the one place to edit if a new domain's field names differ — a
# MAGIC   natural next step is to move it into a `bronze.field_mapping_config`
# MAGIC   table, same pattern as `domain_config`.
# MAGIC - **Auto schema evolution**: schema is inferred fresh from each domain's
# MAGIC   batch via `schema_of_json`, and every write uses `mergeSchema = true`,
# MAGIC   so new JSON fields appear as new columns automatically.
# MAGIC - **List-or-single-object safe**: `ContactInformation` sub-nodes
# MAGIC   (EMedia/Phone/Address) are sometimes a single JSON object and sometimes
# MAGIC   an array depending on the payload. A small helper detects which, and
# MAGIC   wraps single objects in an array before exploding, so both shapes
# MAGIC   produce exactly one row per contact point.
# MAGIC - **Latest batch is resolved per domain from `sland_mdm` itself**
# MAGIC   (content-detected `domain_code`), joined to `batch_control` for
# MAGIC   `COMPLETED` status — not from the folder-implied domain — so it stays
# MAGIC   correct even if a file was ever landed in the "wrong" domain's folder.

