# MAGIC ## 2.10 — Helper: Safe Explode (handles single-object OR array JSON nodes)

# COMMAND ----------

def safe_explode(df, fk_col, node_col, node_alias):
    """
    Explodes a nested JSON node that may be either a single struct or an
    array of structs, depending on the payload — always yields one row
    per contact point either way, with the FK column preserved alongside.
    NULL nodes yield one null-valued row (via explode_outer), so parent
    rows are never dropped.
    """
    dtype = df.schema[node_col].dataType
    node_expr = F.col(node_col) if isinstance(dtype, ArrayType) else F.array(F.col(node_col))
    return df.select(fk_col, F.explode_outer(node_expr).alias(node_alias))

