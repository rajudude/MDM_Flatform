# MAGIC %md
# MAGIC ## 2.9 — Resolve Latest Completed Batch, Per Domain — Skip if Already Parsed
# MAGIC For each domain, find the latest `COMPLETED` landing batch (from
# MAGIC `sland_mdm` + `batch_control`, as before), then check `parse_control`:
# MAGIC - If that exact `(domain_code, batch_id)` already has a `COMPLETED` parse
# MAGIC   record → **skip** (0 records processed on this run).
# MAGIC - Otherwise → this batch is new (or previously `FAILED`) and gets parsed.
# MAGIC
# MAGIC This is the idempotency gate: running the notebook twice in a row against
# MAGIC the same Step 1 batch does real work only once.

# COMMAND ----------

from pyspark.sql import functions as F, types as T
from pyspark.sql.types import ArrayType

latest_landing_batches = spark.sql("""
    SELECT s.domain_code, MAX(s.batch_id) AS batch_id
    FROM   bronze.sland_mdm s
    JOIN   bronze.batch_control bc ON bc.batch_id = s.batch_id
    WHERE  bc.status = 'COMPLETED'
    GROUP  BY s.domain_code
""").collect()

already_parsed = {
    (r["domain_code"], r["batch_id"])
    for r in spark.sql("""
        SELECT domain_code, batch_id
        FROM   bronze.parse_control
        WHERE  status = 'COMPLETED'
    """).collect()
}

latest_batches = []
print(">>> Latest completed landing batch per domain:")
for row in latest_landing_batches:
    domain_code, batch_id = row["domain_code"], row["batch_id"]
    if (domain_code, batch_id) in already_parsed:
        print(f"    {domain_code}: batch_id = {batch_id} — already parsed, SKIPPING (0 records)")
    else:
        print(f"    {domain_code}: batch_id = {batch_id} — new, will parse")
        latest_batches.append(row)

if not latest_batches:
    print("\n>>> Nothing new to parse for any domain. Step 2 exiting — 0 records processed.")

